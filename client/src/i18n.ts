export type StrKey = keyof typeof STRINGS;

export function tr(lang: Lang, key: StrKey, vars?: Record<string, string | number>): string {
  const entry = STRINGS[key] as T | undefined;
  if (!entry) return '';
  let s = entry[lang] ?? entry.en;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function pickLang(code: string | undefined): Lang {
  const c = (code ?? '').toLowerCase();
  if (c.startsWith('ru') || c.startsWith('uk') || c.startsWith('be') || c.startsWith('kk')) return 'ru';
  if (c.startsWith('en')) return 'en';
  return 'uz';
}
